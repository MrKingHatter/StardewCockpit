// One-time dev codegen: turns the oshawk Rust `assets/*.json` into js/predictor-data.js.
// Mirrors build.rs `generate_cart_16`. Run: node tools/gen-predictor-data.mjs [assetsDir]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ASSETS = process.argv[2] ||
  'c:\\PProj\\stardew predictor\\stardew-predictor oshawk\\assets';
const OUT = new URL('../js/predictor-data.js', import.meta.url);

const U16MAX = 65535;

// JSON.parse reorders integer-like keys; the game uses file (insertion) order, so
// scan the raw text for the top-level object keys in the order they appear.
function topLevelKeysInOrder(text) {
  const keys = [];
  let depth = 0, i = 0;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    if (c === '"') {
      let j = i + 1, s = '';
      while (j < n) {
        const d = text[j];
        if (d === '\\') { s += text[j + 1]; j += 2; continue; }
        if (d === '"') break;
        s += d; j++;
      }
      let k = j + 1;
      while (k < n && /\s/.test(text[k])) k++;
      if (depth === 1 && text[k] === ':') keys.push(s);
      i = j + 1;
      continue;
    }
    if (c === '{' || c === '[') depth++;
    else if (c === '}' || c === ']') depth--;
    i++;
  }
  return keys;
}

function parseU16(key) {
  if (/^\d+$/.test(key)) {
    const v = Number(key);
    if (v >= 0 && v <= U16MAX) return v;
  }
  return U16MAX;
}

// --- Objects.json -> ALL_OBJECTS (file order) + ELIGIBLE pool ---------------
const objText = readFileSync(join(ASSETS, 'Objects.json'), 'utf8');
const objMap = JSON.parse(objText);
const orderedKeys = topLevelKeysInOrder(objText);

const allObjects = [];
const eligible = [];
const objSprite = {}; // numeric id -> SpriteIndex (springobjects sheet only)
let eligIdx = 0;

for (const key of orderedKeys) {
  const v = objMap[key];
  const name = v.Name;
  const price = (v.Price | 0);
  const type = v.Type;
  const category = (v.Category | 0);
  const exclude = v.ExcludeFromRandomSale === true;
  const id = parseU16(key);
  const blockedType = type === 'Quest' || type === 'Minerals' || type === 'Arch';

  const idNumeric = /^\d+$/.test(key) ? Number(key) : null;
  // Sprite index into springobjects.png (only when the default texture is used).
  const texture = v.Texture || '';
  if (idNumeric !== null && (texture === '' || /springobjects/i.test(texture))) {
    objSprite[idNumeric] = v.SpriteIndex | 0;
  }
  // Layer 1 (RANDOM_ITEMS): numeric id in [2,789], not excluded, price > 0.
  const passesRandomItems =
    idNumeric !== null && idNumeric >= 2 && idNumeric <= 789 && !exclude && price > 0;
  // Layer 2 (PerItemCondition): Category < 0 && != -999, Type not Quest/Minerals/Arch.
  const passesCondition =
    passesRandomItems && category < 0 && category !== -999 && !blockedType;

  let eli = -1;
  if (passesCondition) {
    eli = eligIdx++;
    eligible.push({ id, name, price: price & U16MAX });
  }

  allObjects.push({
    id,
    name,
    price: Math.max(0, price),
    off: exclude,
    cat: category,
    blk: blockedType,
    eli,
  });
}

// --- Furniture16.json / Shirts16.json (array order) -------------------------
function loadPool(file) {
  const arr = JSON.parse(readFileSync(join(ASSETS, file), 'utf8'));
  return arr.map((f) => ({
    id: typeof f.id === 'number' ? (f.id & U16MAX) : U16MAX,
    name: f.name,
    price: f.price | 0,
    off: f.offlimits === true,
  }));
}
const furniture = loadPool('Furniture16.json');
const shirts = loadPool('Shirts16.json');

// --- Emit -------------------------------------------------------------------
const j = (x) => JSON.stringify(x);
const rows = (arr) => arr.map((r) => '  ' + j(r)).join(',\n');

const out = `// AUTO-GENERATED by tools/gen-predictor-data.mjs from the oshawk 1.6 assets.
// Do not edit by hand. Objects are in Stardew's dictionary (file) order.
// Row fields: id (65535 = non-numeric key), name, price, off (ExcludeFromRandomSale),
// cat (Category), blk (Type in Quest/Minerals/Arch), eli (index into PRED_ELIGIBLE or -1).
const PRED_ALL_OBJECTS = [
${rows(allObjects)}
];
const PRED_ELIGIBLE = [
${rows(eligible)}
];
const PRED_FURNITURE = [
${rows(furniture)}
];
const PRED_SHIRTS = [
${rows(shirts)}
];
const PRED_OBJ_SPRITE = ${JSON.stringify(objSprite)};
`;

writeFileSync(OUT, out);
console.log(
  `wrote predictor-data.js: ${allObjects.length} objects, ${eligible.length} eligible, ` +
  `${furniture.length} furniture, ${shirts.length} shirts`
);
